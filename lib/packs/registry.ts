const BY_ID: ReadonlyMap<PackId, IndustryPack> = new Map(
  INDUSTRY_PACKS.map((pack) => [pack.id, pack]),
)

export const PACK_IDS: readonly PackId[] = INDUSTRY_PACKS.map((pack) => pack.id)

export function getPack(id: string): IndustryPack | null {
  return BY_ID.get(id as PackId) ?? null
}

export function requirePack(id: string): IndustryPack {
  const pack = getPack(id)
  if (!pack) {
    throw new Error(`Unknown industry pack: ${id}`)
  }
  return pack
}

export function listPacksByCategory(): Record<PackCategory, IndustryPack[]> {
  const groups: Record<PackCategory, IndustryPack[]> = {
    trading: [],
    hospitality: [],
    health: [],
    education: [],
    services: [],
    operations: [],
    general: [],
  }
  for (const pack of INDUSTRY_PACKS) {
    groups[pack.category].push(pack)
  }
  return groups
}

export function packsReadyForVertical(): IndustryPack[] {
  return INDUSTRY_PACKS.filter((pack) => pack.verticalStatus === 'ready')
}

export function packsPlannedVertical(): IndustryPack[] {
  return INDUSTRY_PACKS.filter((pack) => pack.verticalStatus === 'planned')
}
